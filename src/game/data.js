/** A named answer with a rarity tier and optional extra spellings. */
function answer(name, tier, aliases) {
  return aliases ? { name, tier, aliases } : { name, tier };
}

/** A named item with a number, for "closest to" gauge rounds. */
function metric(name, value, aliases) {
  return aliases ? { name, value, aliases } : { name, value };
}

